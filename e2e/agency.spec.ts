async function seedMarketed(purpose: 'sale' | 'rent'): Promise<{ id: string; slug: string; instructionId: string }> {
  const p = await seedPublishedProperty({ purpose, title: `E2E HagerLand ${purpose} ${Date.now()}`, price: purpose === 'sale' ? 6_000_000 : 30_000 })
  const { data, error } = await db()
    .from('agency_instructions')
    .insert({ purpose, title: `E2E instruction ${purpose}`, stage: 'live', fee_type: 'percent', fee_percent: 2, agency_type: 'sole', term_start: '2026-10-01', property_id: p.id, asking_price_etb: purpose === 'sale' ? 6_000_000 : 30_000 })
    .select('id')
    .single()
  if (error || !data) throw error
  return { id: p.id, slug: p.slug, instructionId: data.id }
}

async function adminSave(page: Page, button: string, message: RegExp | string) {
  await page.getByRole('button', { name: button }).click()
  await expect(page.getByText(message).first()).toBeVisible()
}

