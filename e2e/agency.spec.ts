test('the agency switch: off hides agency pages and listing actions; on restores them', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'admin at desktop width')
  const listing = await seedMarketed('sale')
  await adminSession(page)
  try {
    await page.goto('/roodber8/pillars')
    await page.getByRole('switch', { name: 'Direct for HagerLand estate agency' }).click()
    await expect(page.getByText('Direct is now off for HagerLand estate agency.')).toBeVisible()
    expect((await page.goto('/agency'))?.status()).toBe(404)
    expect((await page.goto('/agency/valuation'))?.status()).toBe(404)
    await page.goto(`/property/${listing.slug}`)
    await expect(page.getByRole('link', { name: 'Book a viewing' })).toHaveCount(0)
  } finally {
    await setPillarModes('estate-agency', { direct: true }, { service: true })
    await page.goto('/roodber8/pillars')
    await page.getByRole('switch', { name: 'Interest capture for HagerLand estate agency' }).click()
    await expect(page.getByText('Interest capture is now on for HagerLand estate agency.')).toBeVisible()
    await page.reload()
    await page.getByRole('switch', { name: 'Interest capture for HagerLand estate agency' }).click()
    await expect(page.getByText('Interest capture is now off for HagerLand estate agency.')).toBeVisible()
  }
  expect((await page.goto('/agency'))?.status()).toBe(200)
  await page.goto(`/property/${listing.slug}`)
  await expect(page.getByRole('link', { name: 'Book a viewing' })).toBeVisible()
})
